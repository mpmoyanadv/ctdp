CREATE TABLE app_users (
    id UUID PRIMARY KEY,
    email VARCHAR(160) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    sa_id_number VARCHAR(20),
    phone_number VARCHAR(30),
    account_number VARCHAR(30),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    user_domain VARCHAR(40) NOT NULL,
    partner_institution VARCHAR(120),
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    locked_reason VARCHAR(500),
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_users_email UNIQUE (email)
);

CREATE TABLE bank_transactions (
    id UUID PRIMARY KEY,
    customer_id UUID NOT NULL,
    transaction_reference VARCHAR(48) NOT NULL,
    merchant_name VARCHAR(180) NOT NULL,
    payment_rail VARCHAR(48) NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    card_last_four VARCHAR(12),
    location VARCHAR(255),
    transacted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT uq_bank_transactions_ref UNIQUE (transaction_reference),
    CONSTRAINT fk_bank_transactions_customer FOREIGN KEY (customer_id) REFERENCES app_users (id)
);

CREATE INDEX idx_bank_transactions_customer_id ON bank_transactions (customer_id, transacted_at DESC);

CREATE TABLE disputes (
    id UUID PRIMARY KEY,
    dispute_reference VARCHAR(40) NOT NULL,
    transaction_id UUID,
    merchant_name VARCHAR(180) NOT NULL,
    payment_rail VARCHAR(48),
    customer_id UUID NOT NULL,
    assigned_user_id UUID,
    assigned_domain VARCHAR(40) NOT NULL,
    status VARCHAR(40) NOT NULL,
    category VARCHAR(60) NOT NULL,
    source_channel VARCHAR(30) NOT NULL,
    contact_channel_metadata VARCHAR(255),
    amount NUMERIC(15, 2) NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    resolution_summary VARCHAR(2000),
    original_dispute_id UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_disputes_reference UNIQUE (dispute_reference),
    CONSTRAINT fk_disputes_transaction FOREIGN KEY (transaction_id) REFERENCES bank_transactions (id),
    CONSTRAINT fk_disputes_customer FOREIGN KEY (customer_id) REFERENCES app_users (id),
    CONSTRAINT fk_disputes_assigned_user FOREIGN KEY (assigned_user_id) REFERENCES app_users (id),
    CONSTRAINT fk_disputes_original FOREIGN KEY (original_dispute_id) REFERENCES disputes (id)
);

CREATE INDEX idx_disputes_customer_id ON disputes (customer_id, created_at DESC);
CREATE INDEX idx_disputes_domain ON disputes (assigned_domain, created_at DESC);
CREATE INDEX idx_disputes_status ON disputes (status);
CREATE INDEX idx_disputes_created_at ON disputes (created_at DESC);
CREATE INDEX idx_disputes_transaction_id ON disputes (transaction_id);

CREATE TABLE dispute_attachments (
    id UUID PRIMARY KEY,
    dispute_id UUID NOT NULL,
    uploaded_by UUID NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    checksum_sha256 VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_attachments_dispute FOREIGN KEY (dispute_id) REFERENCES disputes (id),
    CONSTRAINT fk_attachments_uploader FOREIGN KEY (uploaded_by) REFERENCES app_users (id)
);

CREATE INDEX idx_dispute_attachments_dispute_id ON dispute_attachments (dispute_id, created_at ASC);

CREATE TABLE dispute_notes (
    id UUID PRIMARY KEY,
    dispute_id UUID NOT NULL,
    author_id UUID NOT NULL,
    author_name VARCHAR(160) NOT NULL,
    author_role VARCHAR(32) NOT NULL,
    message VARCHAR(3000) NOT NULL,
    internal_only BOOLEAN NOT NULL DEFAULT FALSE,
    requires_customer_reply BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notes_dispute FOREIGN KEY (dispute_id) REFERENCES disputes (id),
    CONSTRAINT fk_notes_author FOREIGN KEY (author_id) REFERENCES app_users (id)
);

CREATE INDEX idx_dispute_notes_dispute_id ON dispute_notes (dispute_id, created_at ASC);

CREATE TABLE staff_work_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id UUID NOT NULL,
    staff_id UUID NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    total_duration_seconds BIGINT,
    CONSTRAINT fk_work_sessions_dispute FOREIGN KEY (dispute_id) REFERENCES disputes (id),
    CONSTRAINT fk_work_sessions_staff FOREIGN KEY (staff_id) REFERENCES app_users (id)
);

CREATE INDEX idx_staff_work_sessions_dispute ON staff_work_sessions (dispute_id, completed_at);
CREATE INDEX idx_staff_work_sessions_staff ON staff_work_sessions (staff_id, started_at DESC);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id UUID,
    actor_email VARCHAR(160),
    severity VARCHAR(24) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    entity_name VARCHAR(80) NOT NULL,
    entity_id VARCHAR(255) NOT NULL,
    ip_address VARCHAR(64),
    metadata TEXT,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_logs_timestamp ON audit_logs (timestamp DESC);
CREATE INDEX idx_audit_logs_actor_id ON audit_logs (actor_id);
CREATE INDEX idx_audit_logs_event_type ON audit_logs (event_type);

CREATE TABLE fraud_alert_tokens (
    id UUID PRIMARY KEY,
    token VARCHAR(128) NOT NULL,
    user_id UUID NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_fraud_alert_tokens_token UNIQUE (token),
    CONSTRAINT fk_fraud_tokens_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE INDEX idx_fraud_alert_tokens_user_id ON fraud_alert_tokens (user_id);

CREATE TABLE password_reset_otps (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    email VARCHAR(160) NOT NULL,
    otp_hash VARCHAR(120) NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_password_reset_otps_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE INDEX idx_password_reset_otps_user_active ON password_reset_otps (user_id, used, created_at DESC);
